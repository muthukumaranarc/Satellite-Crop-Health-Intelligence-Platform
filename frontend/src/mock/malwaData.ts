// Helper to generate rectangular field polygon around a base point [lat, lng]
function createFieldPolygon(id: string, name: string, block: string, crop: string, areaHa: number, ndvi: number, ndre: number, healthClass: any, stressScore: number, baseLat: number, baseLng: number, widthDeg = 0.004, heightDeg = 0.003) {
  const minLat = baseLat;
  const maxLat = baseLat + heightDeg;
  const minLng = baseLng;
  const maxLng = baseLng + widthDeg;

  return {
    type: 'Feature' as const,
    properties: {
      id,
      name,
      block,
      crop,
      areaHa,
      ndvi,
      ndre,
      healthClass,
      stressScore,
      lastObservation: 'May 20, 2024',
    },
    geometry: {
      type: 'Polygon' as const,
      coordinates: [
        [
          [minLng, minLat],
          [maxLng, minLat],
          [maxLng, maxLat],
          [minLng, maxLat],
          [minLng, minLat],
        ],
      ],
    },
  };
}

